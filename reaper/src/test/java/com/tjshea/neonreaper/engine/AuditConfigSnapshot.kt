package com.tjshea.neonreaper.engine

import java.io.File

/**
 * Plain-text dump of every number the money maths depends on (reel strips, pay table, paylines, feature weights, vault
 * parameters), taken from the REAL [ReaperConfig]. The independent audit tools in tools/audit (C enumerator, numpy
 * simulator, policy optimiser) read this file, so they audit the shipped constants and not a transcription of them.
 * [AuditTest.configSnapshotIsCurrent] fails when the committed copy tools/audit/config_snapshot.txt goes stale.
 */
object AuditConfigSnapshot {
    private fun ints(a: IntArray) = a.joinToString(" ")
    private fun dbls(a: DoubleArray) = a.joinToString(" ") { it.toString() }

    fun text(): String {
        val c = ReaperConfig
        val sb = StringBuilder()
        fun line(key: String, vararg v: String) { sb.append(key); for (x in v) sb.append(' ').append(x); sb.append('\n') }
        line("# generated by AuditTest.configSnapshotIsCurrent from ReaperConfig.kt - do not edit by hand")
        line("dims", c.REELS.toString(), c.ROWS.toString(), c.SYMBOL_COUNT.toString(), c.WILD.toString(), c.SCATTER.toString())
        for (s in 0 until c.SYMBOL_COUNT) line("pay", s.toString(), ints(c.PAYS[s]))
        for (l in c.PAYLINES.indices) line("payline", ints(c.PAYLINES[l]))
        for (r in 0 until c.REELS) line("strip", r.toString(), ints(c.STRIPS[r]))
        for (r in 0 until c.REELS) line("fsstrip", r.toString(), ints(c.FS_STRIPS[r]))
        line("scatter_pay", ints(c.SCATTER_PAY)); line("fs_spins", ints(c.FS_SPINS)); line("fs_extra", ints(c.FS_EXTRA))
        line("fs_ramp_cap", c.FS_RAMP_CAP.toString()); line("max_seance_spins", Seance.MAX_SPINS.toString())
        line("max_win_tokens", c.MAX_WIN_TOKENS.toString()); line("stakes", ints(c.STAKES))
        line("buy_x", c.BUY_SEANCE_X.toString(), c.BUY_VAULT_X.toString())
        line("feature_rate", c.FEATURE_RATE.toString()); line("mini_weights", dbls(c.MINI_WEIGHTS))
        for (i in c.FEATURE_PATTERNS.indices) line("reaper_pattern", c.FEATURE_WEIGHTS[i].toString(), ints(c.FEATURE_PATTERNS[i]))
        line("raven_wilds", ints(c.RAVEN_WILDS)); line("raven_weights", dbls(c.RAVEN_WILD_WEIGHTS))
        line("coin_counts", ints(c.COIN_COUNTS)); line("coin_count_weights", dbls(c.COIN_COUNT_WEIGHTS))
        line("coin_values", ints(c.COIN_VALUES)); line("coin_weights", dbls(c.COIN_WEIGHTS))
        line("skull_mults", ints(c.SKULL_MULTS)); line("skull_weights", dbls(c.SKULL_MULT_WEIGHTS)); line("skull_wilds", c.SKULL_WILDS.toString())
        line("relic", c.RELIC_COUNT.toString(), c.RELIC_CHANCE.toString())
        line("vault_dims", c.VAULT_COLS.toString(), c.VAULT_ROWS.toString(), c.VAULT_START_ORBS.toString(), c.VAULT_RESPINS.toString(), c.VAULT_ORB_CHANCE.toString())
        line("orb_values", ints(c.ORB_VALUES)); line("orb_weights", ints(c.ORB_WEIGHTS))
        line("vault_special", c.P_MAJOR.toString(), c.P_MINOR.toString(), c.P_MINI.toString(), c.P_REAPER.toString())
        line("vault_values", c.MINI.toString(), c.MINOR.toString(), c.MAJOR.toString(), c.GRAND.toString())
        line("rtp_by_stake_claimed", dbls(c.RTP_BY_STAKE))
        return sb.toString()
    }

    /** The committed snapshot (tools/audit/config_snapshot.txt) or null; works whatever the working directory of the test JVM is. */
    fun committed(): File? = listOf("../tools/audit/config_snapshot.txt", "tools/audit/config_snapshot.txt").map { File(it) }.firstOrNull { it.exists() }
}
